export function getHintForWord(word: string, categoryId?: string | null): string {
  const own = categoryId ? HINTS_BY_CATEGORY[categoryId]?.[word] : undefined;
  if (own) return own;
  for (const bank of Object.values(HINTS_BY_CATEGORY)) {
    if (bank[word]) return bank[word];
  }
  return "No hint available";
}
